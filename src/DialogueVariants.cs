        sealed class Rotation {
            public readonly Dictionary<string, Queue<int>> Bags = new Dictionary<string, Queue<int>>();
            public readonly Dictionary<string, int> Last = new Dictionary<string, int>();
        }
        static readonly ConditionalWeakTable<Pet, Rotation> rotations = new ConditionalWeakTable<Pet, Rotation>();
        static readonly Random speechRandom = new Random();
        internal static string[] Options(Pet p,int situation,string original,string need=null) {
            var extra=additions[p.SpeciesId<0?0:p.SpeciesId+1][situation].Split('|');
            var result=new string[4];result[0]=original;
            for(int i=0;i<3;i++)result[i+1]=need==null?extra[i]:extra[i].Replace("{need}",need);
            return result;
        }
        static string Choose(Pet p,int situation,string original,string need=null) {
            var options=Options(p,situation,original,need);
            string key=p.SpeciesId+":"+situation+":"+need;
            lock(speechRandom) {
                var state=rotations.GetOrCreateValue(p);Queue<int> bag;
                if(!state.Bags.TryGetValue(key,out bag)||bag.Count==0) {
                    int[] order={0,1,2,3};
                    for(int i=3;i>0;i--){int j=speechRandom.Next(i+1);int temp=order[i];order[i]=order[j];order[j]=temp;}
                    int last;if(state.Last.TryGetValue(key,out last)&&order[0]==last){int j=speechRandom.Next(1,4);int temp=order[0];order[0]=order[j];order[j]=temp;}
                    bag=new Queue<int>(order);state.Bags[key]=bag;
                }
                int chosen=bag.Dequeue();state.Last[key]=chosen;return options[chosen];
            }
        }
        public static string Skill(Pet p,string original){return Choose(p,9,original);}
        public static string Idle(Pet p,string original){return Choose(p,3,original);}
